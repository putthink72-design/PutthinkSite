export type LegalBlock =
  | { type: "updated"; text: string }
  | { type: "heading"; text: string }
  | { type: "paragraph"; text: string }
  | { type: "bullets"; items: string[] }
  | { type: "link"; href: string };

/** Parse numbered sections / bullets / URLs for LegalDocument */
export function parseLegal(text: string): {
  title: string;
  blocks: LegalBlock[];
} {
  const lines = text.split("\n");
  const title = (lines[0] ?? "").trim();
  const blocks: LegalBlock[] = [];
  let bullets: string[] = [];

  const flushBullets = () => {
    if (bullets.length === 0) return;
    blocks.push({ type: "bullets", items: bullets });
    bullets = [];
  };

  const numberedRemainder = (line: string): string | null => {
    const dot = line.indexOf(".");
    if (dot <= 0) return null;
    const num = line.slice(0, dot);
    if (![...num].every((c) => c >= "0" && c <= "9")) return null;
    const rest = line.slice(dot + 1).trim();
    return rest || null;
  };

  const isHeading = (line: string): boolean => {
    const rest = numberedRemainder(line);
    if (!rest) return false;
    const endsLikeSentence =
      rest.endsWith(".") || rest.endsWith("。") || rest.endsWith("다.");
    if (endsLikeSentence || rest.length > 60) return false;
    return true;
  };

  for (const raw of lines.slice(1)) {
    const line = raw.trim();
    if (!line) {
      flushBullets();
      continue;
    }
    if (
      line.startsWith("Last updated") ||
      line.startsWith("최종 업데이트") ||
      line.startsWith("最終更新")
    ) {
      flushBullets();
      blocks.push({ type: "updated", text: line });
      continue;
    }
    if (line.startsWith("•")) {
      bullets.push(line.slice(1).trim());
      continue;
    }
    if (isHeading(line)) {
      flushBullets();
      blocks.push({ type: "heading", text: line });
      continue;
    }
    flushBullets();
    if (line.startsWith("http")) {
      blocks.push({ type: "link", href: line });
    } else {
      const urlIdx = line.lastIndexOf("https://");
      if (urlIdx >= 0) {
        const href = line.slice(urlIdx).trim();
        const para = line.slice(0, urlIdx).replace(/[:\s]+$/, "").trim();
        if (para) blocks.push({ type: "paragraph", text: para });
        blocks.push({ type: "link", href });
      } else {
        blocks.push({ type: "paragraph", text: line });
      }
    }
  }
  flushBullets();
  return { title, blocks };
}
